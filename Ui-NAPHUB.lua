-- แปลงข้อความเป็นตัวเลข รองรับ 1,000,000 / 500k / 2m
local function parseAmount(text)
    text = tostring(text or ""):lower():gsub("[%s,]", "")
    local num, suffix = text:match("^(%d+%.?%d*)([kmb]?)$")
    num = tonumber(num)
    if not num then return nil end
    local mult = ({ k = 1e3, m = 1e6, b = 1e9 })[suffix] or 1
    local value = math.floor(num * mult)
    return value >= 1 and value or nil
