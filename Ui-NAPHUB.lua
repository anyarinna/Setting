-- require โมดูลของเกม (ลองธรรมดาก่อน แล้วค่อยลองสลับ identity 2)
local LoadedModules, FailedModules = {}, {}
local function requireAsGame(module)
    local done, ok, loaded = false, false, nil
    task.spawn(function()
        pcall(setthreadidentity, 2)
        local read, identity = pcall(getthreadidentity)
        if read and identity == 2 then
            ok, loaded = pcall(require, module)
        end
        done = true
    end)
    local deadline = os.clock() + SEASON_CFG.RequireTimeout
    while not done and os.clock() < deadline do
        task.wait()
    end
    return ok, loaded
end

local function needModule(module)
    if not module then error("ไม่พบโมดูลของเกม (เกมอาจอัปเดต)", 0) end
    if LoadedModules[module] ~= nil then return LoadedModules[module] end
    if FailedModules[module] then
        error(("อ่านข้อมูลเกม %s ไม่ได้บน executor นี้"):format(module.Name), 0)
    end
    local ok, loaded = pcall(require, module)
    if not ok then
        local firstErr = loaded
        ok, loaded = requireAsGame(module)
        if not ok then
            FailedModules[module] = tostring(firstErr)
            error(("อ่านข้อมูลเกม %s ไม่ได้บน executor นี้"):format(module.Name), 0)
        end
    end
    LoadedModules[module] = loaded
    return loaded
end

-- หา Remote ของเกม (รองรับโฟลเดอร์ที่ต่อท้าย _Server)
local function findRemote(folder, name)
    local root = ReplicatedStorage:FindFirstChild("Remote")
    if not root then return nil end
    for _, holderName in ipairs({ folder .. "_Server", folder }) do
        local holder = root:FindFirstChild(holderName)
        local remote = holder and holder:FindFirstChild(name)
        if remote then return remote end
    end
    return root:FindFirstChild(name, true)
end

local function getRemote(folder, name)
    local remote = findRemote(folder, name)
    if remote then return remote end
    local root = ReplicatedStorage:WaitForChild("Remote", SEASON_CFG.RemoteTimeout)
    local holder = root and (root:FindFirstChild(folder .. "_Server") or root:WaitForChild(folder, SEASON_CFG.RemoteTimeout))
    remote = holder and holder:WaitForChild(name, SEASON_CFG.RemoteTimeout) or findRemote(folder, name)
    if not remote then error(("ไม่พบ remote %s.%s"):format(folder, name), 0) end
    return remote
end

local function tierOf(id)
    return tonumber(tostring(id):match("%d+")) or 0
end

local function highestKey(tbl)
    local bestKey, bestTier = nil, -1
    for key in pairs(tbl) do
        local tier = tierOf(key)
        if tier > bestTier then bestKey, bestTier = key, tier end
    end
    return bestKey
end

local function abbreviate(number)
    local units = { "", "K", "M", "B", "T", "Qa", "Qi", "Sx", "Sp" }
    local index = 1
    while number >= 1000 and index < #units do
        number /= 1000
        index += 1
    end
    if index == 1 then return tostring(math.floor(number)) end
    return ("%.2f%s"):format(number, units[index])
end

local function waitAll(workers, job)
    local pending = workers
    for _ = 1, workers do
        task.spawn(function()
            pcall(job)
            pending -= 1
        end)
    end
    local deadline = os.clock() + SEASON_CFG.RemoteTimeout * 3
    while pending > 0 and os.clock() < deadline do
        task.wait(0.1)
    end
end

