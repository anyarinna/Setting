-- ดึงตรรกะจาก LOOT_TO_FORGE-NAPHUB: ยิง StageFinishedRF ที่ Stage_27 เป็นชุดๆ
-- แล้วเก็บหินด้วย GetEnhantStoneRE จนจำนวนในกระเป๋าถึงเป้าหมาย
---------------------------------------------------------------------
local EMBER_CFG = { StageId = "Stage_27", StoneId = "EnhantStone_1", BatchSize = 35, WaitTime = 0.12 }

---@param targetAmount number  จำนวนที่ต้องการเพิ่ม
---@param onProgress function?  ส่ง (gained, target) ทุกรอบ
---@param shouldStop function?  คืน true เมื่อต้องการหยุด (ปิดสวิตช์)
---@return number, number, string  gained, finalCount, reason ("done" | "manual" | "timeout")
function Backend.PumpEmberStones(targetAmount, onProgress, shouldStop)
    local stageRemote = getRemote("Stage", "StageFinishedRF")
    local stoneRemote = getRemote("Stage", "GetEnhantStoneRE")
    local backpackData = needModule(findPath("LocalData.BackpackData"))

    -- นับเฉพาะ EnhantStone_1 จริง (ข้ามรายการที่ UUID ขึ้นต้น SSS-MAT)
    local function getStoneCount()
        local total = 0
        local bp = backpackData.GetData()
        if bp and bp.have then
            for key, item in pairs(bp.have) do
                if type(item) == "table" and item.ID == EMBER_CFG.StoneId and not tostring(key):find("^SSS%-MAT") then
                    total += item.Number or 0
                end
            end
        end
        return total
    end

    -- เก็บของที่ดรอปจากด่าน (UUID ขึ้นต้น SSS- หรือเป็น table)
    local function claimDrops(drops)
        if type(drops) ~= "table" then return end
        if type(drops.Drops) == "table" then drops = drops.Drops end
        for uuid, itm in pairs(drops) do
            if type(uuid) == "string" and (uuid:sub(1, 4) == "SSS-" or type(itm) == "table") then
                pcall(function() stoneRemote:FireServer(uuid) end)
            end
        end
    end

    local initialCount = getStoneCount()
    local goal = initialCount + targetAmount
    local current = initialCount
    local t0 = os.clock()
    local maxWait = math.max(60, math.ceil(targetAmount / 5000) * 60)
    local batchSize, waitTime, stalls = EMBER_CFG.BatchSize, EMBER_CFG.WaitTime, 0

    while current < goal and (os.clock() - t0) < maxWait and not (shouldStop and shouldStop()) do
        local before = current
        local n = (goal - current < 50) and math.min(batchSize, 15) or batchSize
        for _ = 1, n do
            task.spawn(function()
                if shouldStop and shouldStop() then return end
                local ok, drops = pcall(function() return stageRemote:InvokeServer(EMBER_CFG.StageId) end)
                if ok then claimDrops(drops) end
            end)
        end
        task.wait(waitTime)
        current = getStoneCount()
        if _G._TwoK_HealBackpack then pcall(_G._TwoK_HealBackpack) end
        if onProgress then onProgress(math.max(0, current - initialCount), targetAmount) end
        -- ถ้าจำนวนไม่ขยับหลายรอบ ลดความถี่ลงกันเซิร์ฟเวอร์ปฏิเสธ
        if current <= before then
            stalls += 1
            if stalls >= 5 then
                batchSize = math.max(1, math.floor(batchSize / 2))
                waitTime = math.min(1, waitTime * 2)
                stalls = 0
            end
        else
            stalls = 0
        end
    end

    local finalCount = getStoneCount()
    pcall(function()
        local bpGui = require(ReplicatedStorage.GuiUtils.BackpackGUI)
        if bpGui and bpGui.UpdateBackpack then bpGui.UpdateBackpack() end
    end)
    local gained = math.max(0, finalCount - initialCount)
    local reason = "timeout"
    if shouldStop and shouldStop() then
        reason = "manual"
    elseif gained >= targetAmount then
        reason = "done"
    end
    return gained, finalCount, reason
end

